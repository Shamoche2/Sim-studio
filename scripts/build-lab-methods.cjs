// Collects the Method steps from every virtual lab into sims/howto/labs.js (used by the teacher guide).
// Run: node scripts/build-lab-methods.cjs
const fs = require("fs"), path = require("path"), vm = require("vm");
const root = path.join(__dirname, "..", "sims", "labs"), out = {};
for (const subject of fs.readdirSync(root)) for (const file of fs.readdirSync(path.join(root, subject))) {
  const id = subject + "/" + file.replace(/\.js$/, "");
  const noop = new Proxy(function () {}, { get: () => noop, apply: () => noop });
  const ctx = { Sim: noop, Lab: (cfg) => (out[id] = { method: cfg.method, equipment: cfg.equipment, safety: cfg.safety }), Math, console };
  ctx.Lab.round = (v) => v; ctx.Lab.noise = (v) => v;
  vm.runInNewContext(fs.readFileSync(path.join(root, subject, file), "utf8"), ctx);
}
fs.writeFileSync(path.join(__dirname, "..", "sims", "howto", "labs.js"), "// Generated by scripts/build-lab-methods.cjs. Do not edit by hand.\nwindow.LABHOWTO = " + JSON.stringify(out, null, 1) + ";\n");
console.log("labs:", Object.keys(out).length);
